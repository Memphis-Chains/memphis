//! The native arm of the block-format parity gate.
//!
//! ## Why this test exists
//!
//! Two writers write chain blocks on this host: the TypeScript write path
//! and the native data plane. They wrote DIFFERENT BYTES for the same
//! logical block — the native arm sorted every key by byte (because
//! `serde_json`'s `Map` is a `BTreeMap`), the TypeScript arm used the
//! order of its object literals. Measured 2026-11-23 over every block
//! file in `~/.memphis/chains`: 6 248 files in the native order and
//! 5 606 in the TypeScript order, in the same chains.
//!
//! `chain verify` cannot see that. The hash covers a block's VALUES, not
//! its bytes, so two files that differ only in key order verify
//! identically — and no gate ever noticed.
//!
//! The hash had a second copy of the same kind of problem: the payload
//! rule (`type`, `content`, `tags`) lived in three places on the
//! TypeScript side and twice on this one, and the two arms' fallback —
//! what a payload without a string `content` gets as its content — was
//! different code. `JSON.stringify(data)` keeps the payload's key order;
//! `data.to_string()` sorts it. For a payload whose keys were not
//! already sorted, the two arms would have hashed the same logical block
//! differently.
//!
//! ## What the gate does
//!
//! `tests/fixtures/block-format-parity.json` holds the logical cases and
//! the values THIS core produces for them — generated by
//! `cargo run -p memphis-core --example emit_block_format_parity`, never
//! hand-written.
//!
//! This test checks the native arm against that artefact, and
//! `tests/unit/block-format-parity.test.ts` checks the TypeScript arm
//! against the SAME artefact. If the two arms ever diverge, one of the
//! two tests fails.

use memphis_core::block_format::{normalize_block_payload, serialize_block_for_disk};
use memphis_core::hash::compute_hash_of_payload;
use serde_json::Value;
use sha2::{Digest, Sha256};

const FIXTURE: &str = include_str!("../../../tests/fixtures/block-format-parity.json");

fn fixture_cases() -> Vec<Value> {
    let document: Value =
        serde_json::from_str(FIXTURE).expect("the block-format fixture must be valid JSON");
    document
        .get("cases")
        .and_then(Value::as_array)
        .cloned()
        .expect("the block-format fixture must carry a cases array")
}

fn sha256_hex(bytes: &[u8]) -> String {
    let mut hasher = Sha256::new();
    hasher.update(bytes);
    format!("{:x}", hasher.finalize())
}

#[test]
fn the_native_arm_produces_the_bytes_the_fixture_carries() {
    let cases = fixture_cases();
    assert!(!cases.is_empty(), "the block-format fixture must not be empty");

    let mut problems: Vec<String> = Vec::new();
    let mut previous: Option<String> = None;

    for case in &cases {
        let name = case.get("name").and_then(Value::as_str).unwrap_or("<unnamed>");
        let block = case.get("block").expect("a case must carry a block");
        let index = block["index"].as_u64().expect("a block needs an index");
        let timestamp = block["timestamp"].as_str().expect("a block needs a timestamp");
        let chain = block["chain"].as_str().expect("a block needs a chain");
        let prev_hash = block["prev_hash"].as_str().expect("a block needs a prev_hash");
        let data = &block["data"];

        // The cases are a chain: each block links to the one before it.
        if let Some(expected_prev) = previous.as_ref() {
            if prev_hash != expected_prev {
                problems.push(format!(
                    "{name}: prev_hash {prev_hash} does not link to the previous block {expected_prev}"
                ));
            }
        }

        let payload = normalize_block_payload(data);
        let hash = compute_hash_of_payload(index, timestamp, chain, &payload, prev_hash);

        let file_block = serde_json::json!({
            "index": index,
            "timestamp": timestamp,
            "chain": chain,
            "data": payload,
            "prev_hash": prev_hash,
            "hash": hash,
        });
        let bytes = serialize_block_for_disk(&file_block);

        let expected_payload = case.get("expected_payload").expect("a case needs a payload");
        if &payload != expected_payload {
            problems.push(format!(
                "{name}: the payload is {payload}, the fixture carries {expected_payload}"
            ));
        }

        let expected_hash = case
            .get("expected_hash")
            .and_then(Value::as_str)
            .expect("a case needs a hash");
        if hash != expected_hash {
            problems.push(format!(
                "{name}: the hash is {hash}, the fixture carries {expected_hash}"
            ));
        }

        let expected_file = case
            .get("expected_file_sha256")
            .and_then(Value::as_str)
            .expect("a case needs a file digest");
        let file_digest = sha256_hex(&bytes);
        if file_digest != expected_file {
            problems.push(format!(
                "{name}: the file bytes digest to {file_digest}, the fixture carries {expected_file}"
            ));
        }

        previous = Some(hash);
    }

    assert!(
        problems.is_empty(),
        "the native arm and the block-format fixture disagree:\n{}",
        problems.join("\n")
    );
}

#[test]
fn the_first_fixture_block_links_to_the_genesis_hash() {
    let cases = fixture_cases();
    let first = cases
        .first()
        .and_then(|case| case.get("block"))
        .and_then(|block| block.get("prev_hash"))
        .and_then(Value::as_str)
        .expect("the first case must carry a prev_hash");
    assert_eq!(
        first,
        "0".repeat(64),
        "the block-format chain must start at the genesis hash"
    );
}

#[test]
fn the_keys_are_sorted_by_byte_and_not_by_locale() {
    // The `mixed-case-keys` case is the discriminator. A locale-aware
    // sort puts `apple` before `Bravo` and `Zebra`; a byte sort puts
    // `Bravo`, `Zebra`, `apple`. The native arm sorts by byte, and the
    // TypeScript arm has to agree with it byte for byte.
    let cases = fixture_cases();
    let case = cases
        .iter()
        .find(|case| case.get("name").and_then(Value::as_str) == Some("mixed-case-keys"))
        .expect("the fixture must carry the mixed-case-keys case");

    let payload = normalize_block_payload(&case["block"]["data"]);
    let keys: Vec<&String> = payload.as_object().expect("a payload is an object").keys().collect();

    let position = |needle: &str| {
        keys.iter()
            .position(|key| key.as_str() == needle)
            .unwrap_or_else(|| panic!("the payload must carry {needle}"))
    };
    assert!(
        position("Bravo") < position("Zebra") && position("Zebra") < position("apple"),
        "the payload keys must be sorted by byte, got {keys:?}"
    );
}
