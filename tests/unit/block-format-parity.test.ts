import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

import { describe, expect, it } from 'vitest';

import { normalizeBlockPayload } from '../../src/core/block-payload.js';
import { canonicalHash } from '../../src/core/chain-hash.js';
import { serializeBlockForDisk } from '../../src/infra/storage/chain-file-io.js';

/**
 * The TypeScript arm of the block-format parity gate.
 *
 * ## Why this file exists
 *
 * Two writers write chain blocks on this host: the TypeScript write path
 * and the native data plane (`crates/memphis-operator/src/chat_memory.rs`).
 * They wrote DIFFERENT BYTES for the same logical block — the native arm
 * sorted every key by byte (because `serde_json`'s `Map` is a `BTreeMap`),
 * the TypeScript arm used the order of its object literals.
 *
 * Measured 2026-11-23 over every block file in `~/.memphis/chains`: 6 248
 * files in the native order and 5 606 in the TypeScript order, in the
 * same chains. `chain verify` cannot see that — the hash covers a block's
 * VALUES, not its bytes, so two files that differ only in key order
 * verify identically, and no gate ever noticed.
 *
 * The payload rule (`type`, `content`, `tags`) had the same shape of
 * problem: three copies on this side, and a fallback that disagreed with
 * the native core. `JSON.stringify(data)` keeps the payload's key order;
 * the core's `data.to_string()` sorts it. For a payload whose keys were
 * not already sorted, the two arms would have hashed the same logical
 * block differently.
 *
 * ## What the gate does
 *
 * `tests/fixtures/block-format-parity.json` holds the logical cases and
 * the values the NATIVE CORE produces for them, generated by
 * `cargo run -p memphis-core --example emit_block_format_parity` — never
 * hand-written.
 *
 * This file checks the TypeScript arm against that artefact;
 * `crates/memphis-core/tests/block_format_parity.rs` checks the native
 * arm against the SAME artefact. If the two arms ever diverge, one of
 * the two tests fails.
 */

interface ParityCase {
  name: string;
  why?: string;
  block: {
    index: number;
    timestamp: string;
    chain: string;
    data: Record<string, unknown>;
    prev_hash: string;
  };
  expected_payload: Record<string, unknown>;
  expected_hash: string;
  expected_file_sha256: string;
}

interface ParityFixture {
  $comment?: string;
  cases: ParityCase[];
}

const fixture: ParityFixture = JSON.parse(
  readFileSync(join(process.cwd(), 'tests', 'fixtures', 'block-format-parity.json'), 'utf8'),
) as ParityFixture;

function sha256Hex(bytes: string): string {
  return createHash('sha256').update(bytes, 'utf8').digest('hex');
}

/**
 * The same payload with its keys in the opposite order.
 *
 * The TypeScript arm receives a payload as a JavaScript object, and the
 * order of that object's keys is the CALLER's business — the same payload
 * reaches the native arm as a `serde_json::Value`, whose keys are sorted
 * by byte. The two arms therefore see different key orders for the same
 * logical payload, and the canonical hash must not depend on which order
 * the arm received.
 *
 * This is the discriminator for the fallback branch: a payload with no
 * string `content` gets the canonical JSON of the payload as its content,
 * and that JSON has to be SORTED — otherwise the two arms hash the same
 * logical block differently.
 */
function reversedKeys(data: Record<string, unknown>): Record<string, unknown> {
  return Object.fromEntries(Object.entries(data).reverse());
}

describe('the TypeScript block writer agrees with the native core', () => {
  it('produces the payload the fixture carries', () => {
    expect(fixture.cases.length).toBeGreaterThan(0);

    for (const testCase of fixture.cases) {
      expect(normalizeBlockPayload(testCase.block.data), testCase.name).toEqual(
        testCase.expected_payload,
      );
    }
  });

  it('computes the hash the core computed, for every fixture case', () => {
    for (const testCase of fixture.cases) {
      const { block } = testCase;
      const hash = canonicalHash({
        index: block.index,
        timestamp: block.timestamp,
        chain: block.chain,
        data: block.data,
        prev_hash: block.prev_hash,
      });

      expect(hash, testCase.name).toBe(testCase.expected_hash);
    }
  });

  it('computes the same hash whatever order the payload arrived in', () => {
    for (const testCase of fixture.cases) {
      const { block } = testCase;
      const hash = canonicalHash({
        index: block.index,
        timestamp: block.timestamp,
        chain: block.chain,
        data: reversedKeys(block.data),
        prev_hash: block.prev_hash,
      });

      expect(hash, `${testCase.name} (reversed key order)`).toBe(testCase.expected_hash);
      expect(normalizeBlockPayload(reversedKeys(block.data)), `${testCase.name} (reversed key order)`).toEqual(
        testCase.expected_payload,
      );
    }
  });

  it('writes the file bytes the core wrote', () => {
    for (const testCase of fixture.cases) {
      const { block } = testCase;
      const payload = normalizeBlockPayload(block.data);
      const hash = canonicalHash({
        index: block.index,
        timestamp: block.timestamp,
        chain: block.chain,
        data: block.data,
        prev_hash: block.prev_hash,
      });

      const bytes = serializeBlockForDisk({
        index: block.index,
        timestamp: block.timestamp,
        chain: block.chain,
        data: payload,
        prev_hash: block.prev_hash,
        hash,
      });

      expect(sha256Hex(bytes), testCase.name).toBe(testCase.expected_file_sha256);
    }
  });

  it('links every case to the one before it', () => {
    for (let index = 1; index < fixture.cases.length; index += 1) {
      const previous = fixture.cases[index - 1]!;
      const current = fixture.cases[index]!;

      expect(current.block.prev_hash, current.name).toBe(previous.expected_hash);
    }
  });

  it('starts the chain at the genesis hash', () => {
    expect(fixture.cases[0]!.block.prev_hash).toBe('0'.repeat(64));
  });

  it('sorts the keys by byte and not by locale', () => {
    // The `mixed-case-keys` case is the discriminator. A locale-aware
    // sort puts `apple` before `Bravo` and `Zebra`; a byte sort puts
    // `Bravo`, `Zebra`, `apple`. The native arm sorts by byte, and this
    // arm has to agree with it byte for byte.
    const testCase = fixture.cases.find((entry) => entry.name === 'mixed-case-keys');
    expect(testCase, 'the fixture must carry the mixed-case-keys case').toBeDefined();

    const keys = Object.keys(testCase!.expected_payload);
    const position = (needle: string): number => keys.indexOf(needle);

    expect(position('Bravo')).toBeGreaterThanOrEqual(0);
    expect(position('Bravo')).toBeLessThan(position('Zebra'));
    expect(position('Zebra')).toBeLessThan(position('apple'));
  });
});
